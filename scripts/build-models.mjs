// Emits plain JS for the models the server imports (public/questions-model.js) from the TypeScript source of truth.
import { transformWithOxc } from 'vite';
import fs from 'node:fs/promises';
const root = new URL('../', import.meta.url);
for (const name of ['questions-model', 'submission-review']) {
  const file = new URL(`web/src/lib/${name}.ts`, root);
  const { code } = await transformWithOxc(await fs.readFile(file, 'utf8'), `${name}.ts`, { lang: 'ts' });
  await fs.writeFile(new URL(`public/${name}.js`, root), `// Generated by scripts/build-models.mjs from web/src/lib/${name}.ts. Do not edit.\n${code}`);
  console.log(`built public/${name}.js`);
}
